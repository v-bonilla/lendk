//! Shims: the frozen v1 shim text, the shim directory's checks, the write lock, and the writes
//! that make the shims match the map.

use crate::cli::Env;
use crate::failure::Failure;
use crate::map::{Scan, path};
use crate::sys;
use std::io::Write;
use std::os::unix::fs::{DirBuilderExt, MetadataExt, OpenOptionsExt, PermissionsExt};
use std::time::{Duration, Instant};

pub const MARKER: &[u8] = b"# lendk shim ";

/// lendk's path for the shims: the path the caller ran, symlinks unresolved, made absolute
/// against the working directory.
pub fn self_path(env: &Env, argv0: &[u8]) -> Vec<u8> {
    let ran = sys::exec_path().unwrap_or_else(|| argv0.to_vec());
    if ran.starts_with(b"/") {
        return ran;
    }
    absolute(env, &ran)
}

/// `rel` made absolute against PWD, when it names the working directory, else `getcwd`.
pub fn absolute(env: &Env, rel: &[u8]) -> Vec<u8> {
    let cwd = match env.get("PWD") {
        Some(pwd) if pwd.starts_with(b"/") && sys::same_file(pwd, b".") => pwd.to_vec(),
        _ => std::env::current_dir()
            .map(|d| std::os::unix::ffi::OsStrExt::as_bytes(d.as_os_str()).to_vec())
            .unwrap_or_default(),
    };
    let rel = rel.strip_prefix(b"./").unwrap_or(rel);
    [&cwd[..], b"/", rel].concat()
}

/// The shim for `cmd`, running lendk at `lendk`.
pub fn text(lendk: &[u8], cmd: &[u8]) -> Vec<u8> {
    let mut quoted = Vec::new();
    for &c in lendk {
        if c == b'\'' {
            quoted.extend_from_slice(b"'\\''");
        } else {
            quoted.push(c);
        }
    }
    [
        &b"#!/bin/sh\n# lendk shim v1: generated by lendk sync, edits are overwritten\nlendk='"[..],
        &quoted,
        b"'\n[ -x \"$lendk\" ] || { echo \"lendk: lendk-missing: $lendk is missing, so ",
        cmd,
        b" did not run. The user must reinstall lendk from its project repository, then run: lendk sync\" >&2; exit 127; }\nexec \"$lendk\" run -- '",
        cmd,
        b"' \"$@\"\n",
    ]
    .concat()
}

/// Whether `file` is a regular file, not a symlink, whose second line carries the shim marker.
pub fn is_shim(file: &[u8]) -> bool {
    if !std::fs::symlink_metadata(path(file)).is_ok_and(|m| m.is_file()) {
        return false;
    }
    let text = std::fs::read(path(file)).unwrap_or_default();
    text.split(|&c| c == b'\n')
        .nth(1)
        .is_some_and(|l| l.starts_with(MARKER))
}

/// Whether `file` has the shim mode 0755.
pub fn mode_ok(file: &[u8]) -> bool {
    std::fs::symlink_metadata(path(file)).is_ok_and(|m| m.is_file() && m.mode() & 0o7777 == 0o755)
}

/// The owner and mode check of `dir` when it exists.
pub fn check_dir(dir: &[u8]) -> Result<(), Failure> {
    if std::fs::symlink_metadata(path(dir)).is_err() {
        return Ok(());
    }
    let fail = |class, text: &[u8]| Failure::new(class, [dir, text].concat()).with("PATH", dir);
    let meta = std::fs::metadata(path(dir));
    if !meta.as_ref().is_ok_and(std::fs::Metadata::is_dir) {
        return Err(fail("write", b": not a directory"));
    }
    let meta = meta.map_err(|_| fail("write", b": not a directory"))?;
    if meta.uid() != sys::euid() {
        return Err(fail("unsafe", b" is owned by another user"));
    }
    if meta.mode() & 0o022 != 0 {
        return Err(fail("unsafe", b" is writable by others"));
    }
    Ok(())
}

/// Every entry of the shim directory, dotfiles after the others, each part sorted.
pub fn files(shims: &[u8]) -> Vec<Vec<u8>> {
    let Ok(dir) = std::fs::read_dir(path(shims)) else {
        return Vec::new();
    };
    let mut names: Vec<Vec<u8>> = dir
        .filter_map(Result::ok)
        .map(|e| std::os::unix::ffi::OsStrExt::as_bytes(e.file_name().as_os_str()).to_vec())
        .collect();
    names.sort_by_key(|n| (n.starts_with(b"."), n.clone()));
    names
        .into_iter()
        .map(|n| [shims, b"/", &n[..]].concat())
        .collect()
}

fn read_line(file: &[u8]) -> Vec<u8> {
    let text = std::fs::read(path(file)).unwrap_or_default();
    text.split(|&c| c == b'\n')
        .next()
        .unwrap_or_default()
        .to_vec()
}

/// SHIMS.lock, held from `take` until drop. While held, HUP, INT and TERM wait, so the call
/// releases the lock and removes its temporary files before such a signal ends it.
pub struct Lock {
    dir: Vec<u8>,
    pub temps: Vec<Vec<u8>>,
    break_empty: Option<(Vec<u8>, u32)>,
}

impl Lock {
    /// Creates the shim directory 0700 under any umask, then holds its lock.
    pub fn take(shims: &[u8], pause: Option<u64>) -> Result<Lock, Failure> {
        std::fs::DirBuilder::new()
            .recursive(true)
            .mode(0o700)
            .create(path(shims))
            .map_err(|_| {
                Failure::new("write", [shims, b": cannot be created"].concat()).with("PATH", shims)
            })?;
        let mut lock = Lock {
            dir: [shims, b".lock"].concat(),
            temps: Vec::new(),
            break_empty: None,
        };
        lock.wait(pause)?;
        Ok(lock)
    }

    /// take_lock: retries for 10 s. A dead owner's lock is broken only by the holder of the
    /// break marker, after rereading the owner, so no two waiters both break it.
    fn wait(&mut self, pause: Option<u64>) -> Result<(), Failure> {
        let end = Instant::now() + Duration::from_secs(11);
        let pid_file = [&self.dir[..], b"/pid"].concat();
        let mut owner = Vec::new();
        let mut empty = 0;
        let mut i = 0;
        while i < 100 && Instant::now() < end {
            i += 1;
            sys::hold_signals(true);
            if std::fs::DirBuilder::new()
                .mode(0o700)
                .create(path(&self.dir))
                .is_ok()
            {
                let written = std::fs::write(path(&pid_file), format!("{}\n", std::process::id()));
                return written.map_err(|_| {
                    Failure::new("write", [&self.dir[..], b": cannot be written"].concat())
                        .with("PATH", self.dir.clone())
                });
            }
            sys::hold_signals(false);
            owner = read_line(&pid_file);
            // An owner between its mkdir and its PID write gets 1 s.
            empty = if owner.is_empty() { empty + 1 } else { 0 };
            if ((!owner.is_empty() && !sys::alive(&owner)) || empty > 10)
                && self.break_lock(&owner, pause)
            {
                empty = 0;
                continue;
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        let owner = if owner.is_empty() {
            b"unknown".to_vec()
        } else {
            owner
        };
        Err(Failure::new(
            "write",
            [&self.dir[..], b": held by PID ", &owner[..], b" for 10 s"].concat(),
        )
        .with("PATH", self.dir.clone()))
    }

    /// break_lock: one attempt to remove SHIMS.lock while it still names the dead `owner`. The
    /// break marker SHIMS.lock.break holds its taker's PID. A waiter takes over a dead taker's
    /// marker by creating break inside it, and so on down, so one live waiter at most holds the
    /// deepest marker; it renames the whole marker tree away when done. A marker without a PID
    /// gets 1 s, like the lock.
    fn break_lock(&mut self, owner: &[u8], pause: Option<u64>) -> bool {
        let marker = [&self.dir[..], b".break"].concat();
        let mut p = marker.clone();
        let mut dead = Vec::new();
        while std::fs::create_dir(path(&p)).is_err() {
            let b = read_line(&[&p[..], b"/pid"].concat());
            if b.is_empty() {
                let count = match &mut self.break_empty {
                    Some((at, n)) if *at == p => {
                        *n += 1;
                        *n
                    }
                    _ => {
                        self.break_empty = Some((p.clone(), 1));
                        1
                    }
                };
                if count <= 10 {
                    return false;
                }
            } else if sys::alive(&b) {
                return false;
            }
            dead = b;
            p.extend_from_slice(b"/break");
        }
        self.break_empty = None;
        let _ = std::fs::write(
            path(&[&p[..], b"/pid"].concat()),
            format!("{}\n", std::process::id()),
        );
        // Tests kill a waiter here, holding the marker.
        if let Some(secs) = pause {
            std::thread::sleep(Duration::from_secs(secs));
        }
        if p != marker {
            let parent = &p[..p.len() - b"/break".len()];
            if read_line(&[parent, b"/pid"].concat()) != dead {
                let _ = std::fs::remove_dir_all(path(&p));
                return false;
            }
        }
        let cur = read_line(&[&self.dir[..], b"/pid"].concat());
        if cur == owner && (cur.is_empty() || !sys::alive(&cur)) {
            let _ = std::fs::remove_dir_all(path(&self.dir));
        }
        // A rename is atomic, so no waiter creates a marker inside a tree being removed.
        let away = [&marker[..], format!(".{}", std::process::id()).as_bytes()].concat();
        let _ = std::fs::remove_dir_all(path(&away));
        let _ = std::fs::rename(path(&marker), path(&away));
        let _ = std::fs::remove_dir_all(path(&away));
        true
    }
}

impl Drop for Lock {
    fn drop(&mut self) {
        for t in &self.temps {
            let _ = std::fs::remove_file(path(t));
        }
        let pid = read_line(&[&self.dir[..], b"/pid"].concat());
        if pid == std::process::id().to_string().as_bytes() {
            let _ = std::fs::remove_dir_all(path(&self.dir));
        }
        sys::hold_signals(false);
    }
}

/// What a write of the shims reports: notices, printed at once, and failures, printed by the
/// caller after the map's violations.
#[derive(Default)]
pub struct Report {
    pub notices: Vec<Vec<u8>>,
    pub failures: Vec<Failure>,
}

/// Writes the shims for `scan`'s commands, running lendk at `lendk`, and removes the shims of
/// unmapped commands. A file that is not a lendk shim stays.
pub fn write(shims: &[u8], lendk: &[u8], scan: &Scan, lock: &mut Lock) -> Report {
    let mut report = Report::default();
    let tmp = [
        shims,
        format!("/.lendk-sync.{}", std::process::id()).as_bytes(),
    ]
    .concat();
    lock.temps.push(tmp.clone());
    // Under the lock no other sync is writing, so any other temporary file is a killed call's.
    for f in files(shims) {
        let name = &f[shims.len() + 1..];
        if name.starts_with(b".lendk-sync.")
            && std::fs::symlink_metadata(path(&f)).is_ok_and(|m| m.is_file())
        {
            let _ = std::fs::remove_file(path(&f));
        }
    }
    let mut foreign = Vec::new();
    for name in &scan.cmds {
        let f = [shims, b"/", name].concat();
        let shim = text(lendk, name);
        if std::fs::symlink_metadata(path(&f)).is_ok() {
            if !is_shim(&f) {
                foreign.push(f);
                continue;
            }
            if std::fs::read(path(&f)).is_ok_and(|c| c == shim) && mode_ok(&f) {
                continue;
            }
        }
        let written = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(path(&tmp))
            .and_then(|mut file| file.write_all(&shim))
            .and_then(|()| {
                std::fs::set_permissions(path(&tmp), std::fs::Permissions::from_mode(0o755))
            })
            .and_then(|()| std::fs::rename(path(&tmp), path(&f)));
        if written.is_err() {
            let _ = std::fs::remove_file(path(&tmp));
            report.failures.push(
                Failure::new("write", [&f[..], b": cannot be written"].concat()).with("PATH", f),
            );
        }
    }
    for f in files(shims) {
        let name = &f[shims.len() + 1..];
        if scan.cmds.iter().any(|c| c == name) {
            continue;
        }
        if is_shim(&f) {
            if std::fs::remove_file(path(&f)).is_err() {
                let failure = Failure::new("write", [&f[..], b": cannot be removed"].concat())
                    .with("PATH", f);
                report.failures.push(failure);
            }
        } else {
            let notice = [
                b"lendk: notice: ",
                &f[..],
                b" is not a lendk shim, so sync leaves it.\n",
            ];
            report.notices.push(notice.concat());
        }
    }
    for f in foreign {
        let text = [&f[..], b": is not a lendk shim, so sync leaves it"].concat();
        report
            .failures
            .push(Failure::new("write", text).with("PATH", f));
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(name: &str) -> Vec<u8> {
        let dir = std::env::temp_dir().join(format!("lendk-shims-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::os::unix::ffi::OsStrExt::as_bytes(dir.as_os_str()).to_vec()
    }

    #[test]
    fn the_shim_is_the_frozen_v1_text_and_quotes_a_single_quote() {
        let frozen = include_bytes!("../test/frozen/shim");
        assert_eq!(text(b"/home/alice/.local/bin/lendk", b"gh"), frozen);
        let shim = text(b"/a/it's/lendk", b"gh");
        assert!(
            shim.split(|&c| c == b'\n')
                .any(|l| l == b"lendk='/a/it'\\''s/lendk'")
        );
    }

    #[test]
    fn a_dead_owners_lock_is_broken_and_released_on_drop() {
        let shims = temp_dir("dead");
        let lock_dir = [&shims[..], b".lock"].concat();
        std::fs::create_dir(path(&lock_dir)).unwrap();
        let mut child = std::process::Command::new("true").spawn().unwrap();
        let dead = child.id();
        child.wait().unwrap();
        std::fs::write(
            path(&[&lock_dir[..], b"/pid"].concat()),
            format!("{dead}\n"),
        )
        .unwrap();
        let lock = Lock::take(&shims, None).unwrap();
        let pid = read_line(&[&lock_dir[..], b"/pid"].concat());
        assert_eq!(pid, std::process::id().to_string().as_bytes());
        drop(lock);
        assert!(std::fs::symlink_metadata(path(&lock_dir)).is_err());
        assert!(std::fs::symlink_metadata(path(&[&lock_dir[..], b".break"].concat())).is_err());
        std::fs::remove_dir_all(path(&shims)).unwrap();
    }

    #[test]
    fn sync_keeps_foreign_files_and_removes_only_unmapped_shims() {
        let shims = temp_dir("write");
        let f = |n: &str| [&shims[..], b"/", n.as_bytes()].concat();
        std::fs::write(path(&f("mine")), "#!/bin/sh\necho mine\n").unwrap();
        std::fs::write(path(&f("gone")), "#!/bin/sh\n# lendk shim v0\n").unwrap();
        std::fs::write(path(&f("gh")), "#!/bin/sh\necho mine\n").unwrap();
        let map = [&shims[..], b".map"].concat();
        std::fs::write(path(&map), "gh K\nstub K\n").unwrap();
        let scan = crate::map::scan(&map);
        std::fs::remove_file(path(&map)).unwrap();
        let mut lock = Lock::take(&shims, None).unwrap();
        let report = write(&shims, b"/bin/lendk", &scan, &mut lock);
        drop(lock);
        assert_eq!(
            std::fs::read(path(&f("stub"))).unwrap(),
            text(b"/bin/lendk", b"stub")
        );
        assert!(mode_ok(&f("stub")));
        assert!(std::fs::symlink_metadata(path(&f("gone"))).is_err());
        assert_eq!(
            std::fs::read(path(&f("gh"))).unwrap(),
            b"#!/bin/sh\necho mine\n"
        );
        assert_eq!(report.notices.len(), 1);
        assert_eq!(report.failures.len(), 1);
        let want = [&f("gh")[..], b": is not a lendk shim, so sync leaves it"].concat();
        assert_eq!(report.failures[0].text, want);
        std::fs::remove_dir_all(path(&shims)).unwrap();
    }
}
